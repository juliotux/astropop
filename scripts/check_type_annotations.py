"""Check annotation coverage without importing scientific or online modules."""

from __future__ import annotations

import ast
from pathlib import Path


def check_package(package: Path) -> tuple[int, list[str]]:
    """Return the number of checked functions and missing signature types."""
    count = 0
    failures = []
    for path in sorted(package.rglob('*.py')):
        if path.name == 'version.py':  # generated by setuptools-scm
            continue
        tree = ast.parse(path.read_text(), filename=str(path), type_comments=True)
        parents = {child: parent for parent in ast.walk(tree)
                   for child in ast.iter_child_nodes(parent)}
        for node in ast.walk(tree):
            if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            count += 1
            parameters = [*node.args.posonlyargs, *node.args.args,
                          *node.args.kwonlyargs]
            parameters += [arg for arg in (node.args.vararg, node.args.kwarg)
                           if arg is not None]
            scope = parents.get(node)
            while scope is not None and not isinstance(
                scope, (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef, ast.Module)
            ):
                scope = parents.get(scope)
            if (isinstance(scope, ast.ClassDef) and parameters
                    and parameters[0].arg in ('self', 'cls')):
                parameters = parameters[1:]
            if node.type_comment:
                # Astropy evaluate methods use complete PEP 484 comments:
                # inline evaluate annotations have a runtime meaning as units.
                signature = ast.parse(node.type_comment, mode='func_type')
                if len(signature.argtypes) != len(parameters):
                    failures.append(f'{path}:{node.lineno}: incomplete type comment')
                continue
            missing = [arg.arg for arg in parameters if arg.annotation is None]
            if node.returns is None:
                missing.append('return')
            if missing:
                failures.append(f'{path}:{node.lineno}: {node.name}: '
                                + ', '.join(missing))
    return count, failures


def main() -> None:
    """Check package signatures and fail on missing annotations."""
    package = Path(__file__).resolve().parents[1] / 'astropop'
    count, failures = check_package(package)
    if failures:
        raise SystemExit('\n'.join(failures))
    print(f'All {count} package function signatures are annotated '
          '(excluding generated version.py)')


if __name__ == '__main__':
    main()
